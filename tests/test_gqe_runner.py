# ── Subprocess environment ───────────────────────────────────────────────

def test_env_prepends_the_shim_directory(tmp_path):
    """
    The external factory does `import dmet_excitation_pool` as a top-level
    absolute import. The shim directory must come FIRST, so a stale copy
    inside the checkout cannot shadow the package's implementation.
    """
    cfg = _cfg(tmp_path)
    env = gqe_runner.build_env(cfg, tmp_path,
                               base_env={"PYTHONPATH": "/somewhere/else"})
    first = env["PYTHONPATH"].split(os.pathsep)[0]
    assert first.endswith("_gqe_shims")
    assert "/somewhere/else" in env["PYTHONPATH"], "existing entries kept"


def test_env_sets_the_cudaq_backend(tmp_path):
    """The external repo never calls set_target(), so this is the only lever."""
    cfg = _cfg(tmp_path, gqe=GqeSettings(cudaq_target="nvidia"))
    env = gqe_runner.build_env(cfg, tmp_path, base_env={})
    assert env["CUDAQ_DEFAULT_SIMULATOR"] == "nvidia"


def test_shim_modules_are_importable_from_the_shim_dir():
    """
    Import the shims exactly the way the subprocess will: by top-level
    name, with only the shim directory on the path.
    """
    code = (
        "import importlib.util, sys\n"
        "for name in ('dmet_molecule_adapter', 'dmet_excitation_pool'):\n"
        "    spec = importlib.util.find_spec(name)\n"
        "    assert spec is not None, name\n"
        "print('ok')\n"
    )
    env = dict(os.environ)
    env["PYTHONPATH"] = os.pathsep.join(
        [str(gqe_runner.SHIM_DIR)] + list(__import__("sys").path)
    )
    out = subprocess.run([__import__("sys").executable, "-c", code],
                         capture_output=True, text=True, env=env, timeout=60)
    assert out.returncode == 0, out.stderr
    assert "ok" in out.stdout


