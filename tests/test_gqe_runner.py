def test_step3_routes_through_dispatch():
    """Not through a hardcoded module path."""
    src = Path(cli.__file__).read_text()
    tree = ast.parse(src)
    run_step = next(n for n in tree.body
                    if isinstance(n, ast.FunctionDef) and n.name == "run_step")
    body = ast.dump(run_step)
    assert "dispatch" in body
    assert "quenais.quantum.solver" not in body, (
        "step 3 must not name a solver module directly"
    )


# ── Import isolation ─────────────────────────────────────────────────────

@pytest.mark.parametrize("module", ["gqe_runner", "gqe_setup"])
def test_runner_and_setup_have_no_solver_imports(module):
    """
    Both are imported during CLI dispatch, so neither may pull in a solver
    stack at module scope.
    """
    path = Path(getattr(gqe_runner if module == "gqe_runner" else gqe_setup,
                        "__file__"))
    tree = ast.parse(path.read_text())
    forbidden = {"cudaq", "tequila", "torch", "qiskit", "pyscf", "gqe_qsci"}
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            name = getattr(node, "module", None) or node.names[0].name
            assert name.split(".")[0] not in forbidden, f"{module}: {name}"


def test_quantum_package_init_is_import_light():
    """`from quenais.quantum import dispatch` must not import any solver."""
    import quenais.quantum

    tree = ast.parse(Path(quenais.quantum.__file__).read_text())
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            name = getattr(node, "module", None) or node.names[0].name
            assert not name.startswith("quenais.quantum."), (
                f"quantum/__init__.py imports {name} eagerly"
            )


