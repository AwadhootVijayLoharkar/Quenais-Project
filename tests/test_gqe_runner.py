def test_all_console_scripts_resolve():
    """Every entry point in setup.cfg must import and be callable."""
    import configparser
    import importlib

    cfg_path = Path(__file__).resolve().parents[1] / "setup.cfg"
    parser = configparser.ConfigParser()
    parser.read(cfg_path)
    scripts = parser["options.entry_points"]["console_scripts"]

    for line in scripts.strip().splitlines():
        if "=" not in line:
            continue
        _name, target = (part.strip() for part in line.split("=", 1))
        module_path, func_name = target.split(":")
        module = importlib.import_module(module_path)
        assert callable(getattr(module, func_name)), target


def test_selftest_suppresses_third_party_output():
    """
    PySCF's logger and the ASF library both write past
    contextlib.redirect_stdout. Only an fd-level redirect covers code we do
    not own, so _quiet must use dup2 rather than a Python-level context.
    """
    from quenais import selftest

    src = Path(selftest.__file__).read_text()
    assert "dup2" in src, "_quiet must redirect at the file-descriptor level"
    assert "os.dup(1)" in src.replace("_os.", "os.")


# ── The shipped patch ────────────────────────────────────────────────────

def _patch_text():
    return gqe_setup.PATCH_PATH.read_text()


def test_patch_is_shipped():
    """Without it, quenais-gqe-setup cannot prepare a clean clone."""
    assert gqe_setup.PATCH_PATH.exists(), (
        f"missing {gqe_setup.PATCH_PATH}. Regenerate with "
        f"quenais-gqe-setup --repo <checkout> --create-patch"
    )


def test_patch_touches_exactly_the_declared_files():
    targets = {line[len("+++ b/"):].strip()
               for line in _patch_text().splitlines()
               if line.startswith("+++ b/")}
    assert targets == set(gqe_setup.PATCHED_FILES), (
        f"patch touches {sorted(targets)}, declared {sorted(gqe_setup.PATCHED_FILES)}"
    )


def test_patch_does_not_carry_the_debug_config():
    """
    configs/trainer/default.yaml held leftover debugging values
    (max_iters 100->50, load_checkpoint true->false, target_var 1e-5->1e-3).
    Shipping them would silently override the package's own settings.
    """
    assert "configs/trainer" not in _patch_text()


def test_patch_registers_both_dmet_pools():
    text = _patch_text()
    assert "+from dmet_excitation_pool import" in text
    for spec in ("dmet_pauli_evolution", "dmet_excitation"):
        assert f'+            case "{spec}":' in text, f"pool spec {spec} unregistered"


def test_patch_makes_the_mpi_flag_authoritative():
    """
    Upstream takes the MPI branch whenever MPI happens to be initialised,
    ignoring sampler.mpi. Both call sites must be fixed, not one.
    """
    text = _patch_text()
    assert text.count("+        if self.mpi and cudaq.mpi.is_initialized():") == 2


def test_patch_emits_the_epoch_log():
    """
    The load-bearing instrumentation hunk. Without it training succeeds and
    the visualisation stage has nothing to parse.
    """
    text = _patch_text()
    assert "+        metrics = self.metric_logger.log_result(self, log_inputs)" in text
    assert '+        print(f"[epoch {self.current_epoch}] {metrics}", flush=True)' in text


def test_patch_is_a_well_formed_unified_diff():
    lines = _patch_text().splitlines()
    assert lines[0].startswith("diff --git ")
    hunks = [ln for ln in lines if ln.startswith("@@")]
    assert len(hunks) >= 4, f"expected at least 4 hunks, found {len(hunks)}"
    for name in gqe_setup.PATCHED_FILES:
        assert f"--- a/{name}" in _patch_text()


def test_create_patch_refuses_an_incomplete_diff(tmp_path, monkeypatch=None):
    """
    git diff reports only uncommitted changes, so a file committed inside
    the submodule silently drops its hunk -- and a partial patch looks
    fine. Writing one over a good patch destroyed it once. Refuse instead.
    """
    repo = tmp_path / "repo"
    repo.mkdir()
    out = tmp_path / "out.patch"
    out.write_text("ORIGINAL PATCH CONTENT")

    partial = (
        "diff --git a/gqe_qsci/factory.py b/gqe_qsci/factory.py\n"
        "--- a/gqe_qsci/factory.py\n"
        "+++ b/gqe_qsci/factory.py\n"
        "@@ -1 +1 @@\n-x\n+y\n"
    )

    class FakeResult:
        returncode = 0
        stdout = partial
        stderr = ""

    original = gqe_setup._git
    gqe_setup._git = lambda *a, **k: FakeResult()
    try:
        with pytest.raises(RuntimeError, match="incomplete patch"):
            gqe_setup.create_patch(repo, out)
    finally:
        gqe_setup._git = original

    assert out.read_text() == "ORIGINAL PATCH CONTENT", (
        "the existing patch must be left untouched when the new one is bad"
    )


# ── Documentation contracts ──────────────────────────────────────────────

def _docs_dir():
    return Path(gqe_setup.PATCH_PATH).parents[1] / "docs"


def test_documented_files_match_the_code():
    """
    The GQE integration doc names the three patched files. If PATCHED_FILES
    changes and the doc does not, the doc becomes a lie.
    """
    text = (_docs_dir() / "gqe_integration.md").read_text()
    for name in gqe_setup.PATCHED_FILES:
        assert name in text, f"docs/gqe_integration.md does not mention {name}"
    assert "configs/trainer/default.yaml" in text, (
        "the doc must explain why the config hunk is excluded"
    )


def test_readme_documents_both_solver_families():
    from quenais.config import GQE_SOLVERS, QISKIT_SOLVERS

    readme = (Path(gqe_setup.PATCH_PATH).parents[1] / "README.md").read_text()
    for name in list(QISKIT_SOLVERS) + list(GQE_SOLVERS):
        assert f"`{name}`" in readme, f"README does not document solver {name}"


def test_limitations_doc_exists_and_covers_the_known_issues():
    text = (_docs_dir() / "limitations.md").read_text().lower()
    for topic in ("active space", "transition metal", "closed-shell",
                  "optimizer-dependent"):
        assert topic in text, f"docs/limitations.md does not cover: {topic}"


def test_readme_documents_performance_levers():
    """
    Partners will ask how to make it faster. The answer must be in the
    README, and must not imply a custom build is needed for correctness --
    it is not, and claiming otherwise would put people off.
    """
    readme = (Path(gqe_setup.PATCH_PATH).parents[1] / "README.md").read_text()

    assert "## Performance" in readme
    for lever in ("OMP_NUM_THREADS", "cudaq_target", "--no-binary pyscf"):
        assert lever in readme, f"performance section omits {lever}"

    assert "None of this changes the numbers" in readme, (
        "the performance section must state plainly that a faster build "
        "does not change results"
    )